# Files generated by the pipeline — excluded from source selection
_INTERMEDIATE_RE = re.compile(r"_(nosilence|subtitled)$", re.IGNORECASE)


def _is_intermediate(path: Path) -> bool:
    return bool(_INTERMEDIATE_RE.search(path.stem))


@dataclass
class Step:
    name: str
    status: str = "pending"   # pending | running | done | error | skipped
    output: str = ""
    progress: float | None = None  # 0-100 when available
    start_time: float | None = None
    end_time: float | None = None


@dataclass
class Job:
    job_id: str
    source: str
    prompt_title: str
    prompt_summary: str
    do_remove_silence: bool
    do_burn_subtitles: bool
    simple_transcript: bool
    language: str
    model: str
    privacy: str
    description_prefix: str = ""
    source_urls: list[str] = field(default_factory=list)
    steps: list[Step] = field(default_factory=list)
    files: dict[str, str] = field(default_factory=dict)
    title: str = ""
    description: str = ""
    status: str = "running"
    video_url: str = ""
    studio_url: str = ""
    start_time: float = field(default_factory=time.time)
    end_time: float | None = None

    def to_dict(self) -> dict[str, Any]:
        now = time.time()
        job_elapsed = (self.end_time - self.start_time) if self.end_time else (now - self.start_time)
        return {
            "job_id": self.job_id,
            "status": self.status,
            "video_url": self.video_url,
            "studio_url": self.studio_url,
            "title": self.title,
            "description": self.description,
            "files": self.files,
            "start_time": self.start_time,
            "elapsed_seconds": round(job_elapsed, 1),
            "steps": [
                {
                    "name": s.name,
                    "status": s.status,
                    "output": s.output,
                    "progress": s.progress,
                    "start_time": s.start_time,
                    "elapsed_seconds": (
                        round(s.end_time - s.start_time, 1) if s.start_time and s.end_time
                        else round(now - s.start_time, 1) if s.start_time
                        else None
                    ),
                    "output_files": [
                        {"path": self.files[k], "name": Path(self.files[k]).name}
                        for k in _STEP_FILE_KEYS[i]
                        if k in self.files and self.files[k]
                    ],
                }
                for i, s in enumerate(self.steps)
            ],
        }


